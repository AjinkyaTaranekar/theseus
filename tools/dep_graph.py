#!/usr/bin/env python3
"""Write docs/tasks/dependencies.md: the task dependency graph as Mermaid, from tasks.csv.

Arrows point from a task to the tasks that need it merged first. Arrows implied by a longer route
are left out. Colors are phases; thick arrows are the critical path (the longest chain, weighting
tasks by size).

    python tools/dep_graph.py
"""
from __future__ import annotations

import csv
import re
from functools import lru_cache
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "docs" / "tasks" / "dependencies.md"
TASK_ID = re.compile(r"^[A-Z]{1,2}\d+$")
WEIGHT = {"S": 1, "M": 2, "L": 4}
PHASES = {  # stage -> (class name, fill, stroke, label)
    "Prep": ("prep", "#d8ecd5", "#3c8a3a", "Prep"),
    "Foundation": ("found", "#dbe7f7", "#3a6fc4", "Foundation"),
    "Beat 1": ("b1", "#fbe3d6", "#d9622b", "Beat 1"),
    "Beat 2": ("b2", "#d8f1e8", "#2e9a78", "Beat 2"),
    "Beats 3 and 4": ("b34", "#dde1e8", "#36456b", "Beats 3 and 4"),
    "Ship": ("ship", "#f8dfe7", "#c94f7c", "Ship"),
}


def main() -> None:
    rows = list(csv.DictReader((HERE / "tasks.csv").open(encoding="utf-8")))
    ids = [r["id"] for r in rows]
    by_id = {r["id"]: r for r in rows}
    needs = {t: [n.strip() for n in re.split(r"[,;]", by_id[t]["needs"]) if TASK_ID.match(n.strip())] for t in ids}

    @lru_cache(None)
    def ancestors(t: str) -> frozenset[str]:
        out: set[str] = set()
        for d in needs[t]:
            out |= {d} | ancestors(d)
        return frozenset(out)

    reduced = {t: [d for d in needs[t] if not any(d in ancestors(o) for o in needs[t] if o != d)] for t in ids}

    @lru_cache(None)
    def finish(t: str) -> int:
        return WEIGHT[by_id[t]["size"]] + max((finish(d) for d in needs[t]), default=0)

    chain = ["S7"] if "S7" in by_id else [max(ids, key=finish)]  # S7 is the submission
    while needs[chain[-1]]:
        chain.append(max(needs[chain[-1]], key=finish))
    chain.reverse()
    critical = set(zip(chain, chain[1:]))
    starts = [t for t in ids if not needs[t]]

    lines = ["flowchart TD"]
    for cls, fill, stroke, _ in PHASES.values():
        lines.append(f"  classDef {cls} fill:{fill},stroke:{stroke},color:#1f2328")
    lines.append("  classDef crit stroke:#1f2328,stroke-width:3px")
    for t in ids:
        title = by_id[t]["title"].replace('"', "'")
        lines.append(f'  {t}["{t}: {title}"]:::{PHASES[by_id[t]["stage"]][0]}')
    for t in ids:
        for d in reduced[t]:
            lines.append(f"  {d} {'==>' if (d, t) in critical else '-->'} {t}")
    lines.append("  class " + ",".join(chain) + " crit")

    legend = ", ".join(label for *_, label in PHASES.values())
    text = [
        "# Task dependencies",
        "",
        "Generated by `python tools/dep_graph.py` from `tools/tasks.csv`. Do not edit by hand.",
        "",
        f"**Start here (they need nothing):** {', '.join(starts)}. The build starts with **F1**.",
        "",
        f"**Critical path, the longest chain to submission, weighting tasks by size ({len(chain)} tasks):** "
        f"{' → '.join(chain)}.",
        "Whoever is free helps there first.",
        "",
        f"Colors are phases: {legend}. Thick arrows and dark borders are the critical path. G tasks are the",
        "gates, where both humans check a beat end to end and record a backup clip.",
        "",
        "```mermaid",
        *lines,
        "```",
        "",
    ]
    OUT.write_text("\n".join(text), encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE.parent)}: {len(ids)} tasks, critical path {' -> '.join(chain)}")


if __name__ == "__main__":
    main()
